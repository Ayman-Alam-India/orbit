const matches = (domain: string, list: string[]) => {
  const d = domain.toLowerCase().replace(/^www\./, '')
  return list.some((entry) => d === entry || d.endsWith(`.${entry}`))
}

export const isEstablished = (domain?: string) => Boolean(domain && matches(domain, ESTABLISHED))
export const isAggregator = (domain?: string) => Boolean(domain && matches(domain, AGGREGATORS))
